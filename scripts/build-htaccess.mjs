#!/usr/bin/env node
/**
 * Generates dist/.htaccess for Hostinger's Apache from public/_redirects.
 *
 * The redirect list stays in one file. Writing the same 17 rules twice, in two
 * syntaxes, is how they drift apart.
 */
import { readFileSync, writeFileSync, readdirSync, unlinkSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join, resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const dist = join(root, 'dist');

if (!existsSync(dist)) {
  console.error('✗ No dist/. Run `npm run build` first.');
  process.exit(1);
}

/**
 * iCloud conflict copies, swept from dist on every build.
 *
 * ~/Documents is synced, and a build writing 200 files while the sync is
 * mid-flight reliably produces "index 2.html", "brief 2.php", a second copy
 * of every font. dist is generated, so deleting them here is safe and saves
 * a manual step before every deploy.
 *
 * check-urls.mjs still fails the build if any turn up in src, public or
 * scripts — there they would be real content, and quietly deleting somebody's
 * file is not a thing a build script gets to do.
 */
let swept = 0;
const sweep = (dir) => {
  for (const f of readdirSync(dir, { recursive: true, withFileTypes: true })) {
    if (!f.isFile() || !/ \d+\.\w+$/.test(f.name)) continue;
    unlinkSync(join(f.parentPath ?? f.path, f.name));
    swept++;
  }
};
sweep(dist);
if (swept) console.log(`  · swept ${swept} iCloud conflict copies from dist/`);

/**
 * SHA-256 hashes for every inline script the build emits.
 *
 * The CSP says `script-src 'self'`, which blocks inline scripts outright. That
 * is invisible in development, where no CSP header is sent, and total in
 * production: the mobile menu never opens, the theme is never restored from
 * storage, and the error logger never loads. It was only found by serving the
 * built site with the real header attached.
 *
 * Hashes rather than 'unsafe-inline': allowing any inline script would defeat
 * the point of having a CSP at all. Each hash covers exactly the bytes between
 * the tags, so a changed script fails closed rather than silently running.
 */
/**
 * Analytics origins, added only when analytics is actually configured.
 *
 * `script-src 'self'` blocks gtag.js outright, and `connect-src 'self'` blocks
 * the beacons it sends. Both fail silently in the browser console — the site
 * looks fine and no data ever arrives — which is the same class of bug that
 * blocked the inline scripts, so it gets the same treatment: derived from the
 * config rather than pasted in, and removed automatically if analytics is
 * switched off.
 */
const siteTs = readFileSync(join(root, 'src/lib/site.ts'), 'utf8');
const gaOn = /analytics:\s*'G-[\w]+'/.test(siteTs);
const gaScript = gaOn ? ' https://www.googletagmanager.com' : '';
const gaConnect = gaOn
  ? ' https://www.google-analytics.com https://analytics.google.com https://*.analytics.google.com https://*.google-analytics.com'
  : '';
const gaImg = gaOn ? ' https://www.google-analytics.com https://*.google-analytics.com' : '';
console.log(`  · analytics origins in CSP: ${gaOn ? 'yes' : 'no'}`);

const inlineHashes = new Set();
const walk = (dir) => {
  for (const f of readdirSync(dir, { recursive: true })) {
    if (typeof f !== 'string' || !f.endsWith('.html')) continue;
    const html = readFileSync(join(dir, f), 'utf8');
    for (const m of html.matchAll(/<script(?![^>]*\bsrc=)([^>]*)>([\s\S]*?)<\/script>/g)) {
      if (/type=["']application\/ld\+json["']/.test(m[1])) continue; // data, not code
      inlineHashes.add(`'sha256-${createHash('sha256').update(m[2], 'utf8').digest('base64')}'`);
    }
  }
};
walk(dist);
console.log(`  · ${inlineHashes.size} inline scripts hashed into the CSP`);

const rules = readFileSync(join(root, 'public/_redirects'), 'utf8')
  .split('\n')
  .map((l) => l.trim())
  .filter((l) => l && !l.startsWith('#'))
  .map((l) => l.split(/\s+/))
  .filter(([from, to]) => from && to);

const redirects = rules
  .map(([from, to, code = '301']) => `Redirect ${code} ${from} ${to}`)
  .join('\n');

const htaccess = `# GENERATED by scripts/build-htaccess.mjs — do not edit by hand.
# Redirects come from public/_redirects. Rebuild with: npm run build

# ── canonical host and scheme, in one hop ──
# sgualda.com without www, over HTTPS. That is what the site declares in every
# canonical, every schema @id and the sitemap, and it is what the old
# WordPress already served, so nothing has to be re-earned.
#
# One rule rather than two: redirecting to HTTPS first and dropping www second
# sent http://www through two 301s, which is a chain, and a chain leaks a
# little of whatever the link was worth at every hop.
RewriteEngine On
RewriteCond %{HTTPS} !=on [OR]
RewriteCond %{HTTP_HOST} ^www\\. [NC]
RewriteRule ^(.*)$ https://sgualda.com/$1 [R=301,L]

# ── trailing slash ──
# Astro writes about/index.html, so /about/ works natively. This sends
# /about to /about/ so the two never both resolve and split the ranking.
RewriteCond %{REQUEST_FILENAME} !-f
RewriteCond %{REQUEST_URI} !\\.(php|xml|txt|json|webmanifest)$
RewriteCond %{REQUEST_URI} !/$
RewriteRule ^(.*)$ /$1/ [R=301,L]

# ── 404 ──
ErrorDocument 404 /404.html

# ── security headers ──
<IfModule mod_headers.c>
  # No third-party origins at all: fonts are served from this domain.
  Header always set Content-Security-Policy "default-src 'self'; script-src 'self'${gaScript} ${[...inlineHashes].join(' ')}; style-src 'self' 'unsafe-inline'; font-src 'self'; img-src 'self' data:${gaImg}; connect-src 'self'${gaConnect}; form-action 'self' https://sgualda.substack.com; frame-ancestors 'none'; base-uri 'self'; object-src 'none'; upgrade-insecure-requests"
  Header always set Strict-Transport-Security "max-age=63072000; includeSubDomains; preload"
  Header always set X-Content-Type-Options "nosniff"
  Header always set Referrer-Policy "strict-origin-when-cross-origin"
  Header always set Permissions-Policy "camera=(), microphone=(), geolocation=(), interest-cohort=()"
  Header always set X-Frame-Options "DENY"

  # Hashed filenames never change contents, so they can be cached forever.
  <FilesMatch "\\.(js|css|woff2)$">
    Header set Cache-Control "public, max-age=31536000, immutable"
  </FilesMatch>
  <FilesMatch "\\.(png|jpg|jpeg|webp|avif|svg|ico)$">
    Header set Cache-Control "public, max-age=2592000"
  </FilesMatch>
  <FilesMatch "\\.html$">
    Header set Cache-Control "public, max-age=0, must-revalidate"
  </FilesMatch>
</IfModule>

# ── compression ──
<IfModule mod_deflate.c>
  AddOutputFilterByType DEFLATE text/html text/css text/plain text/xml application/javascript application/json image/svg+xml
</IfModule>

# ── never serve anything that carries secrets ──
# .env-brief.php belongs one level above public_html. This is the second lock:
# if it ever ends up in here, it still cannot be fetched.
<FilesMatch "^\\.env|\\.(log|sql|bak|old|zip|tar|gz|sqlite|db)$">
  Require all denied
</FilesMatch>

# Leftovers from the WordPress that used to live here. If any survive the
# cleanup they are unreachable rather than exploitable.
<FilesMatch "^(wp-config\\.php|xmlrpc\\.php|readme\\.html|license\\.txt)$">
  Require all denied
</FilesMatch>
RedirectMatch 404 ^/(wp-admin|wp-includes|wp-content)(/|$)

# Directory listings, off.
Options -Indexes

# ── redirects ──
${redirects}
`;

writeFileSync(join(dist, '.htaccess'), htaccess);
console.log(`  ✓ dist/.htaccess written — ${rules.length} redirects`);
